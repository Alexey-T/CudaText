<!-- Sample Svelte component for lexer benchmarking -->
<script>
  let count = 39;
  let name = 'bench';

  function handleClick() {
    count += 1;
  }

  $: doubled = count * 2;
  $: if (count > 10) {
    console.log('count is high:', count);
  }
</script>

<style>
  .counter {
    padding: 16px;
    border: 1px solid #336699;
    border-radius: 8px;
  }
  button {
    background: #ff8800;
    color: white;
  }
</style>

<div class="counter">
  <h1>{name}: {count}</h1>
  <p>doubled = {doubled}</p>
  <button on:click={handleClick}>Click me</button>
  <p class="row-0">row 0: {count * 71}</p>
